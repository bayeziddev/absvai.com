/**
 * Bangla postcode data from Bangladesh-geocode's postcode-bd/postcode.json (pinned copy in
 * data/geo/source/bangladesh-geocode/postcode.json), added on top of the postcodes imported by gen:geo.
 *
 * Outputs
 *   worker/migrations/0007_postcode_bangla.sql   additive migration (safe to run on the live database)
 *   data/geo/reports/postcode-bangla-report.csv  one line per postcode: its Bangla names and what changed
 *
 * What the migration does
 *   1. Adds geo_postcodes.post_office_bn and fills it, so checkout can show "Board Bazar (বোর্ড বাজার)".
 *   2. Confirms the postcodes whose area was linked by spelling similarity (match_status 'fuzzy') when postcode-bd's
 *      Bangla thana name is exactly the linked upazila's Bangla name. It only touches rows that are still 'fuzzy' and
 *      still linked to that upazila, so nothing changed by hand is overwritten. Nothing is guessed: a Bangla name that
 *      matches no upazila leaves the row as it is.
 *   3. Bumps geo_postcode_version so browsers fetch the new list.
 *
 * Run: npm run gen:postcode-bn (after gen:geo; CI checks the output is up to date)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'data/geo/source/bangladesh-geocode');
const BANGLA = /[ঀ-৿]/;

type Entry = { en?: Record<string, string>; bn?: Record<string, string> };
const postcodes = new Map(Object.entries(JSON.parse(readFileSync(join(SRC, 'postcode.json'), 'utf8')) as Record<string, Entry>).map(([k, v]) => [k.trim(), v]));

const upazilaTable = (JSON.parse(readFileSync(join(SRC, 'upazilas.json'), 'utf8')) as Array<{ data?: Array<Record<string, string>> }>).find(t => Array.isArray(t.data))!.data!;
const upazilaBn = new Map(upazilaTable.map(u => [Number(u.id), (u.bn_name ?? '').trim()]));

function parseCsvLine(line: string): string[] {
  const out: string[] = [];
  let cur = '';
  let quoted = false;
  for (let i = 0; i < line.length; i++) {
    const ch = line[i];
    if (quoted) {
      if (ch === '"' && line[i + 1] === '"') { cur += '"'; i++; } else if (ch === '"') quoted = false; else cur += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ',') { out.push(cur); cur = ''; } else cur += ch;
  }
  out.push(cur);
  return out;
}
const [head, ...lines] = readFileSync(join(ROOT, 'data/geo/reports/postcode-match-report.csv'), 'utf8').trim().split('\n');
const cols = parseCsvLine(head);
const report = lines.map(l => Object.fromEntries(parseCsvLine(l).map((v, i) => [cols[i], v])) as Record<string, string>);

const sql = (s: string) => `'${s.replace(/'/g, "''")}'`;
const csvCell = (s: string) => (/[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s);
const NOW = "strftime('%Y-%m-%dT%H:%M:%fZ','now')";

const names: string[] = [];
const confirms: string[] = [];
const out = [['postcode', 'post_office', 'post_office_bn', 'upazila', 'thana_bn', 'upazila_bn', 'match_status', 'result'].join(',')];
let named = 0;
let confirmed = 0;
for (const r of report) {
  const bn = postcodes.get(r.postcode)?.bn ?? {};
  const office = (bn.suboffice ?? '').trim();
  const thana = (bn.thana ?? '').trim();
  const officeBn = BANGLA.test(office) ? office : '';
  if (officeBn) {
    names.push(`UPDATE geo_postcodes SET post_office_bn = ${sql(officeBn)} WHERE postcode = ${sql(r.postcode)} AND post_office = ${sql(r.post_office)};`);
    named++;
  }
  const upBn = r.upazila_id ? upazilaBn.get(Number(r.upazila_id)) ?? '' : '';
  let result = officeBn ? 'Bangla name added' : 'no Bangla name in postcode-bd';
  if (r.match_status === 'fuzzy') {
    if (BANGLA.test(thana) && upBn && thana === upBn) {
      confirms.push(`UPDATE geo_postcodes SET match_status = 'alias', match_note = 'Area confirmed by its Bangla name (postcode-bd)', updated_at = ${NOW} WHERE postcode = ${sql(r.postcode)} AND upazila_id = ${Number(r.upazila_id)} AND match_status = 'fuzzy';`);
      confirmed++;
      result += '; area confirmed by the Bangla thana name';
    } else result += '; area link left as it was (Bangla name does not confirm it)';
  }
  out.push([r.postcode, r.post_office, officeBn, r.upazila, thana, upBn, r.match_status, result].map(csvCell).join(','));
}

const migration = [
  '-- Generated by scripts/gen-postcode-bn.ts from Bangladesh-geocode postcode-bd/postcode.json. Do not edit by hand.',
  `-- ${named} Bangla post office names; ${confirmed} spelling-matched areas confirmed by their Bangla thana name. Additive only:`,
  "-- rows fixed by hand ('manual') and areas the Bangla names do not confirm are left exactly as they are.",
  '',
  'ALTER TABLE geo_postcodes ADD COLUMN post_office_bn TEXT;',
  '',
  ...names,
  '',
  ...confirms,
  '',
  '-- Checkout caches the postcode list by this version; a new one makes browsers fetch the Bangla names.',
  `UPDATE settings SET value = CAST(CAST(value AS INTEGER) + 1 AS TEXT), updated_at = ${NOW} WHERE key = 'geo_postcode_version';`,
  '',
].join('\n');
writeFileSync(join(ROOT, 'worker/migrations/0007_postcode_bangla.sql'), migration);
writeFileSync(join(ROOT, 'data/geo/reports/postcode-bangla-report.csv'), out.join('\n') + '\n');
console.log(`0007_postcode_bangla.sql: ${named} Bangla post office names, ${confirmed} areas confirmed (of ${report.filter(r => r.match_status === 'fuzzy').length} spelling matches).`);
